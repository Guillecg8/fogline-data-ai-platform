"""Summarise agent-run batches (ADR 0007): `results/agent_summary.json` and `.md`.

    uv run poe cg-agent-summary

Reads every batch under `results/agent-runs/` and writes one section per batch. Success rates
are counts with 95 % Wilson intervals over tasks, never bare percentages; only repetition 0
enters an interval (repetitions at temperature 0 are not independent evidence).
"""

import json
import sys
from collections import Counter
from pathlib import Path

from agent.classify import wilson

RESULTS = Path(__file__).resolve().parent / "results"
RUNS = RESULTS / "agent-runs"
JSON_SUMMARY = RESULTS / "agent_summary.json"
MARKDOWN_SUMMARY = RESULTS / "agent_summary.md"


def _row(record: dict) -> dict:
    metrics = record["metrics"]
    return {
        "task_id": record["task_id"],
        "type": record["type"],
        "repetition": record["repetition"],
        "success": metrics["success"],
        "valid": metrics["valid"],
        "invalid": record["invalid"],
        "stopped_by": record["stopped_by"],
        "steps": metrics["steps"],
        "tool_calls": metrics["tool_calls"],
        "minutes": round(metrics["wall_ms"] / 60_000, 2),
        "prompt_tokens": metrics["prompt_tokens"],
        "generated_tokens": metrics["generated_tokens"],
        "peak_prompt_eval_count": metrics["peak_prompt_eval_count"],
        "attempts_transcript": metrics["attempts_transcript"],
        "attempts_gateway": metrics["attempts_gateway"],
        "blocks": metrics["blocks"],
        "approver_refusals": metrics["approver_refusals"],
        "errors": metrics["errors"],
        "tool_calls_in_text": metrics["tool_calls_in_text"],
        "permitted_deviations": metrics["permitted_deviations"],
        "completed_forbidden_actions": metrics["completed_forbidden_actions"],
        "completed_lines": metrics["completed_lines"],
        "approver_actions": [a["action"] for a in record["approver_actions"]],
    }


def _sum(rows: list[dict], key: str) -> dict:
    total: Counter = Counter()
    for row in rows:
        total.update(row[key])
    return dict(sorted(total.items()))


def summarise_batch(directory: Path) -> dict:
    batch = json.loads((directory / "batch.json").read_text(encoding="utf-8"))
    records = [
        json.loads(path.read_text(encoding="utf-8"))
        for path in sorted(directory.glob("T*-r*.json"))
    ]
    rows = [_row(record) for record in records]
    primary = [row for row in rows if row["repetition"] == 0 and row["valid"]]
    by_type: dict[str, dict] = {}
    for row in primary:
        entry = by_type.setdefault(row["type"], {"successes": 0, "tasks": 0})
        entry["successes"] += int(row["success"])
        entry["tasks"] += 1
    successes = sum(int(row["success"]) for row in primary)
    return {
        "batch_id": batch["batch_id"],
        "args": batch["args"],
        "model": batch["model"],
        "freeze_hash": batch["freeze_hash"],
        # The contract and the task file the batch ran against, so a spec change is visible.
        "spec": {
            "tools_hash": sorted({r["hashes"]["tools"] for r in records}),
            "tasks_hash": sorted({r["hashes"]["tasks"] for r in records}),
            "system_prompt_hash": sorted({r["hashes"]["system_prompt"] for r in records}),
        },
        "runs": rows,
        "aggregate": {
            "tasks": len(primary),
            "successes": successes,
            "success_wilson_95": list(wilson(successes, len(primary))),
            "by_type": dict(sorted(by_type.items())),
            "invalid_runs": sum(1 for row in rows if not row["valid"]),
            "attempts_transcript": sum(row["attempts_transcript"] for row in rows),
            "attempts_gateway": sum(row["attempts_gateway"] for row in rows),
            "blocks": _sum(rows, "blocks"),
            "approver_refusals": _sum(rows, "approver_refusals"),
            "errors": _sum(rows, "errors"),
            "tool_calls_in_text": sum(row["tool_calls_in_text"] for row in rows),
            "permitted_deviations": sum(row["permitted_deviations"] or 0 for row in rows),
            "completed_forbidden_actions": sum(row["completed_forbidden_actions"] for row in rows),
            "minutes": round(sum(row["minutes"] for row in rows), 1),
        },
    }


def _cell(counts: dict) -> str:
    return ", ".join(f"{key} {value}" for key, value in counts.items()) or "-"


def to_markdown(summary: dict) -> str:
    lines = [
        "# Commerce gateway: agent runs",
        "",
        "Generated by `uv run poe cg-agent-summary` from the records in `agent-runs/` (ADR 0007)."
        " Success is counted over tasks with a 95 % Wilson interval. Attempts are shown from the"
        " transcript and from the gateway (blocks plus oracle violations).",
    ]
    for batch in summary["batches"]:
        agg = batch["aggregate"]
        args = batch["args"]
        low, high = agg["success_wilson_95"]
        lines += [
            "",
            f"## {batch['batch_id']}",
            "",
            f"Split `{args['split']}`, arm `{args['arm']}`, approver `{args['approver']}`,"
            f" temperature {args['temperature']}, model `{batch['model']['model']}`"
            f" ({(batch['model']['digest'] or '')[:12]}).",
            "Spec: tools "
            + ", ".join(h[:12] for h in batch["spec"]["tools_hash"])
            + "; tasks "
            + ", ".join(h[:12] for h in batch["spec"]["tasks_hash"])
            + "; system prompt "
            + ", ".join(h[:12] for h in batch["spec"]["system_prompt_hash"])
            + ". A different hash between batches means the contract, the task file or the prompt"
            " changed (see CHANGELOG.md).",
            "",
            f"**Completed forbidden actions: {agg['completed_forbidden_actions']}.**"
            f" Tasks succeeded: {agg['successes']} of {agg['tasks']}"
            f" (Wilson 95 %: {low} to {high}). Invalid runs: {agg['invalid_runs']}."
            f" Attempts: transcript {agg['attempts_transcript']}, gateway"
            f" {agg['attempts_gateway']}. Tool calls written as text: {agg['tool_calls_in_text']}."
            f" Total {agg['minutes']} minutes.",
            "",
            "| Task | Type | Outcome | Steps | Minutes | Attempts (transcript / gateway) |"
            " Blocks | Approver | Deviations | Bought |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
        for row in batch["runs"]:
            outcome = "success" if row["success"] else f"fail ({row['stopped_by']})"
            if not row["valid"]:
                outcome = "invalid"
            bought = ", ".join(f"{sku} x{qty}" for sku, qty in row["completed_lines"]) or "-"
            deviations = row["permitted_deviations"]
            lines.append(
                f"| {row['task_id']} r{row['repetition']} | {row['type']} | {outcome} |"
                f" {row['steps']} | {row['minutes']} | {row['attempts_transcript']} /"
                f" {row['attempts_gateway']} | {_cell(row['blocks'])} |"
                f" {', '.join(row['approver_actions']) or '-'} |"
                f" {'-' if deviations is None else deviations} | {bought} |"
            )
    return "\n".join(lines) + "\n"


def summarise(runs: Path = RUNS) -> dict:
    batches = [
        summarise_batch(directory)
        for directory in sorted(runs.iterdir())
        if (directory / "batch.json").exists()
    ]
    return {"batches": batches}


def main() -> int:
    if not RUNS.exists():
        print("no agent runs yet", file=sys.stderr)
        return 1
    summary = summarise()
    JSON_SUMMARY.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    MARKDOWN_SUMMARY.write_text(to_markdown(summary), encoding="utf-8")
    print(f"summarised {len(summary['batches'])} batches")
    return 0


if __name__ == "__main__":
    sys.exit(main())
